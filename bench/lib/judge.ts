// A model judging screenshots: each result against a rubric (the four criteria Anthropic's design harness
// grades on), and each arm's tools as a set (do they all look alike?). The judge sees only screenshots and
// the request, never the arm. It is calibrated against the owner's blind votes, not trusted on its own.
import { execFile } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { claudeHome } from "@hewntools/cli/builders/cli.ts";
import { loadCases } from "./cases.ts";
import { cleanEnv, listResults } from "./run.ts";

/** Looks that read as "generated by an AI", from Anthropic's frontend-design skill and what Hewn's builds show. */
export const AI_TELLS = [
  "every section in an identical rounded card (the SaaS card kit)",
  "a centred single column of form fields as the main view",
  "purple or blue gradient on white",
  "warm cream background with a high-contrast serif display and a terracotta or clay accent",
  "near-black background with an acid-green or vermilion accent",
  "tracked-out ALL-CAPS eyebrow labels above every heading",
  "middle-dot meta strings (\"Kitchen · 3 days ago · due\")",
  "pills and badges on everything",
  "emoji used as icons",
  "one system font at a few sizes, no typographic hierarchy",
];

export interface Score {
  design_quality: number;
  originality: number;
  craft: number;
  usefulness: number;
  tells: string[];
  problems: string[];
  best: string;
  /** design_quality + originality count double, as in Anthropic's harness. */
  total: number;
}

export interface Sameness {
  sameness: number;
  shared_traits: string[];
  tells: string[];
}

const uiSketch = (requirements: string) => requirements.split(/\n(?=UI sketch)/)[1]?.trim() ?? "";

export function scorePrompt(c: { name: string; purpose: string; requirements: string }, shots: string[]): string {
  return [
    "You are a demanding senior product designer reviewing the screen of a small personal tool, built for one person who uses it often.",
    `The tool: ${c.name}. ${c.purpose}`,
    uiSketch(c.requirements) ? `What the owner asked the screen to do:\n${uiSketch(c.requirements)}` : "",
    `Open each of these screenshots with the Read tool (they show the screen filled with realistic data): ${shots.join(", ")}.`,
    "Score each criterion from 1 to 10, where 5 is competent but generic, 7 is good work, 8 would impress a design-literate user and 10 is best in class. Be sceptical: most screens are 4 to 6.",
    "- design_quality: does it feel like a coherent whole: hierarchy, composition, typography, colour, spacing, in light and dark?",
    "- originality: does it have a character of its own, drawn from what the tool is about, or does it look like a template, default components, or the common AI-generated look?",
    "- craft: details: alignment, truncation, density, the phone layout, contrast, states, nothing broken or cut off.",
    "- usefulness: does the screen answer the owner's question at a glance, and make the main action quick?",
    `Also list which of these AI tells appear (quote them as written; empty when none): ${AI_TELLS.map((t) => `"${t}"`).join("; ")}.`,
    'Reply with only a JSON object, no prose and no code fence: {"design_quality": n, "originality": n, "craft": n, "usefulness": n, "tells": [..], "problems": ["the three biggest problems, one short line each"], "best": "the best thing about it, one line"}',
  ]
    .filter(Boolean)
    .join("\n\n");
}

export function samenessPrompt(shots: string[]): string {
  return [
    `These screenshots are the main screens of ${shots.length} different personal tools (each about something else), all made by the same builder. Open each with the Read tool: ${shots.join(", ")}.`,
    "How alike do they look as a set: same palette, type, layout patterns, components, decoration? Score sameness from 1 (each has a clearly different look of its own) to 10 (one template with different data).",
    `List the traits they share, and which of these AI tells recur in more than one: ${AI_TELLS.map((t) => `"${t}"`).join("; ")}.`,
    'Reply with only a JSON object, no prose and no code fence: {"sameness": n, "shared_traits": [..], "tells": [..]}',
  ].join("\n\n");
}

/** The first JSON object in a model's reply. */
export function parseJson<T>(text: string): T {
  const start = text.indexOf("{");
  const end = text.lastIndexOf("}");
  if (start < 0 || end < start) throw new Error(`no JSON in the judge's reply: ${text.slice(0, 200)}`);
  return JSON.parse(text.slice(start, end + 1)) as T;
}

export const total = (s: Pick<Score, "design_quality" | "originality" | "craft" | "usefulness">) => 2 * s.design_quality + 2 * s.originality + s.craft + s.usefulness;

/** Ask Claude Code (read-only, isolated from your settings like the builder) about files in `cwd`. */
function ask(cwd: string, prompt: string, model?: string): Promise<string> {
  const home = claudeHome(join(cwd, ".judge-home"));
  const args = ["-p", prompt, "--output-format", "json", ...(model ? ["--model", model] : []), "--strict-mcp-config", "--mcp-config", '{"mcpServers":{}}', "--setting-sources", "", "--settings", '{"disableAllHooks":true}', "--disable-slash-commands", "--allowedTools", "Read", "--disallowedTools", "Bash", "Edit", "Write"];
  return new Promise((resolve, reject) =>
    execFile("claude", args, { cwd, env: { ...cleanEnv(), ...home.env }, maxBuffer: 16 << 20, timeout: 10 * 60_000 }, (e, out) => {
      home.done();
      rmSync(join(cwd, ".judge-home"), { recursive: true, force: true });
      if (e) return reject(e);
      try {
        const r = JSON.parse(out);
        if (r.is_error) return reject(new Error(String(r.result)));
        resolve(String(r.result));
      } catch {
        reject(new Error(`unexpected output from claude: ${out.slice(0, 200)}`));
      }
    }),
  );
}

async function pool<T>(items: T[], n: number, fn: (x: T) => Promise<void>) {
  const queue = [...items];
  await Promise.all(Array.from({ length: Math.min(n, queue.length) }, async () => {
    while (queue.length) await fn(queue.shift()!);
  }));
}

export async function judgeRun(runDir: string, o: { model?: string; again?: boolean; concurrency?: number; log?: (l: string) => void } = {}) {
  const log = o.log ?? console.log;
  const results = listResults(runDir).filter((r) => r.result?.status === "done");
  const cases = new Map((await loadCases()).map((c) => [c.id, c]));
  const SHOTS = ["shots/desktop-light.png", "shots/desktop-dark.png", "shots/mobile-light.png"];
  await pool(results, o.concurrency ?? 3, async (r) => {
    const file = join(r.dir, "judge.json");
    if (existsSync(file) && !o.again) return;
    const c = cases.get(r.result!.case)!;
    try {
      const s = parseJson<Score>(await ask(r.dir, scorePrompt(c, SHOTS.filter((f) => existsSync(join(r.dir, f)))), o.model));
      s.total = total(s);
      writeFileSync(file, JSON.stringify(s, null, 2));
      log(`judged ${r.result!.arm} / ${r.result!.case} / r${r.result!.rep}: ${s.total}/60`);
    } catch (e) {
      log(`judge failed for ${r.dir}: ${(e as Error).message}`);
    }
  });
  // Each arm's tools as a set, per repetition.
  const sets = new Map<string, typeof results>();
  for (const r of results) {
    const k = `${r.result!.arm}/r${r.result!.rep}`;
    sets.set(k, [...(sets.get(k) ?? []), r]);
  }
  await pool([...sets.entries()].filter(([, rs]) => rs.length >= 3), o.concurrency ?? 3, async ([k, rs]) => {
    const [arm, rep] = k.split("/");
    const file = join(runDir, "results", arm, `sameness-${rep}.json`);
    if (existsSync(file) && !o.again) return;
    try {
      const shots = rs.map((r) => join(r.result!.case, rep, "shots", "desktop-light.png")).filter((f) => existsSync(join(runDir, "results", arm, f)));
      const s = parseJson<Sameness>(await ask(join(runDir, "results", arm), samenessPrompt(shots), o.model));
      writeFileSync(file, JSON.stringify(s, null, 2));
      log(`sameness ${arm} ${rep}: ${s.sameness}/10`);
    } catch (e) {
      log(`sameness failed for ${k}: ${(e as Error).message}`);
    }
  });
}

export const readJudge = (dir: string): Score | undefined => (existsSync(join(dir, "judge.json")) ? JSON.parse(readFileSync(join(dir, "judge.json"), "utf8")) : undefined);
